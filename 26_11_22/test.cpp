#define _CRT_SECURE_NO_WARNINGS 1
#include"func.h"

int main()
{
	// func.h、func.cpp、test.cpp编译链接过程
	// 1.预处理：头文件展开/宏替换/条件编译/去掉注释...
	//	 func.h被展开，func.cpp、test.cpp->func.i、test.i
	// 2.编译：检查语法，生成汇编代码
	//	 func.i、test.i->func.s、test.s
	// 3.汇编：汇编代码转换成二进制机器码
	//	 func.s、test.s->func.o、test.o
	//   o文件是目标文件，每个.o文件里都有一个符号表，用来放函数名及其地址
	// 4.链接：把目标文件合并在一起生成可执行程序，并且把需要的函数地址等链接上
	//	 生成 .exe或a.out（linux）

	func1(1);
	func2(1);

	// 在链接前，各种.cpp文件没有交互
	// 模板是在编译时实例化的
	// 如果模板的声明和定义分离，那么编译时就只知道声明，不知道定义，无法实例化
	// 汇编时也就不会把函数放在符号表里
	// 当链接时，就找不到func1函数的地址，所以发生链接错误
	// 而普通的函数，会放在符号表里，所以可以声明和定义分离
	// 要想让模板也可以声明和定义分离，可以用显示实例化
	// 不过还是推荐模板的声明和定义放在一起
	// 这样编译时就有定义，可以直接实例化了

	return 0;
}